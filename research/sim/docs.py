"""Regenerate the generated parts of the research documents from the scenario library.

    python -m sim.docs            # writes docs/research/WORST_CASES.md and the tables in STRATEGY_COMPARISON.md
    python -m sim.docs --check    # exit 1 if either file is out of date (CI)

WORST_CASES.md is fully generated. STRATEGY_COMPARISON.md is hand-written; only the blocks between
<!-- BEGIN GENERATED:<name> --> and <!-- END GENERATED:<name> --> are replaced.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

from . import library, replay, report, strategies

DOCS = pathlib.Path(__file__).resolve().parents[2] / "docs" / "research"
SEV = {"false_completion": "false completion", "false_regression": "false regression", "wrong_job": "wrong job",
       "lost_data": "lost data", "never_completes": "never completes", "false_under_report": "under-report",
       "flapping": "flapping", "stale_value": "stale value", "regression_true": "true regression (shown as drop)"}


def _seq(obs, outs, limit=14):
    s = library.pms_sequence(obs, outs)
    parts = []
    for t, host, pct, done, reasons in s[:limit]:
        r = [x for x in reasons if x not in ("scope_unconfirmed", "no_identity")]
        parts.append(f"t{t:g} {pct:g}{' DONE' if done else ''}{' [' + ','.join(r) + ']' if r else ''}")
    more = f" ... (+{len(s) - limit})" if len(s) > limit else ""
    return (" -> ".join(parts) + more) if parts else "nothing sent"


def _conclusion(m, obs, outs):
    c = []
    if m["polls"] == 0:
        return "nothing reaches PMS (no value or no booking)"
    if m["false_completion"]:
        first = next((o for o, x in zip(obs, outs) if x["send"] and (x["done"] or (x["pct"] or 0) >= 100)
                      and not (o.get("truth") or {}).get("done")), None)
        tp = (first.get("truth") or {}).get("pct") if first else None
        c.append(f"looks complete (100%/done) while the real progress was {tp:g}%" if tp is not None
                 else "looks complete before it is")
    if m["fr_unexplained"]:
        c.append(f"{m['fr_unexplained']} unexplained drop(s): reads as lost work")
    if m["fr_explained"]:
        c.append(f"{m['fr_explained']} drop(s) labelled with a reason code")
    if m["missed_completion"]:
        c.append("never reaches done although the work is finished")
    if m["wrong_job"]:
        c.append(f"{m['wrong_job']} value(s) land on the wrong project")
    if m["pms_stale"]:
        c.append(f"PMS shows an older value {m['pms_stale']} time(s) (observed_at order)")
    if not c:
        c.append(f"correct within {m['max_err']:g} pts")
    elif m["max_err"]:
        c.append(f"max error {m['max_err']:g} pts")
    return "; ".join(c)


def worst_cases_md(rows):
    rec = strategies.RECOMMENDED
    out = ["# Worst cases for editortrack progress (catalog)", "",
           "Generated by `python -m sim.docs` from `research/sim/scenarios/library/*.json` - do not edit by hand; "
           "edit the scenario JSON and regenerate. Each case is an executable scenario: the engine expands it "
           "into the exact observation stream the server would receive, with ground truth, and every strategy in "
           "`research/sim/strategies.py` is scored on it (see STRATEGY_COMPARISON.md).", "",
           "Reading the sequences: `t<min> <pct>` is each value PMS would store (only changes are sent). "
           "`S0` = what happens today (graded/current clips; conform = duration/offline target). "
           f"`{rec}` = the recommended strategy. Reason codes in brackets.", "",
           f"Catalog size: {len(rows)} scenarios.", "",
           "| id | category | severity | today (S0) | recommended (" + rec + ") |", "|---|---|---|---|---|"]
    for sc, obs, res in rows:
        m0, mr = res["S0"][1], res[rec][1]
        sev = ", ".join(SEV.get(s, s) for s in sc.get("severity") or [])
        out.append(f"| [{sc['id']}](#{sc['id'].lower()}) | {sc['category']} | {sev} | {report.cell(m0)} | {report.cell(mr)} |")
    out += ["", "Cell legend: F false completion, R unexplained false regression, r labelled drop, M never "
            "claims done though finished, W wrong job, L nothing sent; number = max error in points.", ""]
    for sc, obs, res in rows:
        m0, mr = res["S0"][1], res[rec][1]
        out += [f"## {sc['id']}", "", f"**{sc['title']}**", "",
                f"- category: {sc['category']} - severity: {', '.join(SEV.get(s, s) for s in sc.get('severity') or [])}"
                f" - stage: {sc.get('stage', 'color')}",
                f"- story: {sc.get('story', '')}",
                f"- raw signals the poller sees: {sc.get('signals', '')}"]
        if sc.get("truth_note"):
            out.append(f"- ground truth: {sc['truth_note']}")
        out += [f"- today (S0), PMS receives: {_seq(obs, res['S0'][0])}",
                f"- today, PMS concludes: {_conclusion(m0, obs, res['S0'][0])}",
                f"- {rec}, PMS receives: {_seq(obs, res[rec][0])}",
                f"- {rec}, PMS concludes: {_conclusion(mr, obs, res[rec][0])}"]
        if sc.get("resolve_unverified"):
            out.append(f"- needs a real Resolve machine: {sc['resolve_unverified']}")
        for k, v in (sc.get("known_limits") or {}).items():
            out.append(f"- known limit ({k}): {v}")
        out.append("")
    return "\n".join(out) + "\n"


def matrix_block(rows):
    return report.matrix(rows)


def fill(text, name, body):
    pat = re.compile(rf"(<!-- BEGIN GENERATED:{name} -->\n).*?(<!-- END GENERATED:{name} -->)", re.S)
    if not pat.search(text):
        raise SystemExit(f"marker {name} missing")
    return pat.sub(lambda m: m.group(1) + body.rstrip() + "\n" + m.group(2), text)


def build():
    rows = report.evaluate_library()
    agg = report.aggregate(rows)
    wc = worst_cases_md(rows)
    sc_path = DOCS / "STRATEGY_COMPARISON.md"
    text = sc_path.read_text(encoding="utf-8")
    text = fill(text, "aggregate", report.aggregate_table(agg, len(rows)))
    text = fill(text, "strategies", report.strategy_table(agg))
    text = fill(text, "matrix", matrix_block(rows))
    text = fill(text, "confirmed", report.confirmed_table())
    fx = replay.run([replay.REPO / "server" / "tests" / "fixtures" / "replay"])
    text = fill(text, "replay", replay.markdown(fx, detail=()))
    return {DOCS / "WORST_CASES.md": wc, sc_path: text}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    stale = []
    for path, body in build().items():
        cur = path.read_text(encoding="utf-8") if path.exists() else None
        if cur != body:
            stale.append(path)
            if not a.check:
                path.write_text(body, encoding="utf-8")
    if a.check and stale:
        print("out of date:", *stale)
        return 1
    print("updated:" if stale else "up to date", *stale)
    return 0


if __name__ == "__main__":
    sys.exit(main())
